#!/usr/bin/env python3
"""Builds js/skin-corpus.js: color palettes sampled from classic skins in the Winamp Skin Museum
(https://skins.webamp.org). Only colors are kept (no skin artwork), plus each skin's name and
museum id so the app can credit the skin a generated design was inspired by.

Usage:  python3 tools/build_skin_corpus.py [count]      (needs Pillow: pip install pillow)
"""
import io, json, re, sys, time, urllib.request
from statistics import median
from PIL import Image

API = 'https://api.webamp.org/graphql'
COUNT = int(sys.argv[1]) if len(sys.argv) > 1 else 400
PAGE = 50
QUERY = '''query ($first: Int!, $offset: Int!) { skins(first: $first, offset: $offset, sort: MUSEUM) {
  nodes { md5 filename nsfw screenshot_url ... on ClassicSkin { archive_files { filename text_content } } } } }'''

def gql(first, offset):
    body = json.dumps({'query': QUERY, 'variables': {'first': first, 'offset': offset}}).encode()
    req = urllib.request.Request(API, body, {'content-type': 'application/json', 'user-agent': 'music-box-skin-corpus'})
    return json.load(urllib.request.urlopen(req, timeout=60))['data']['skins']['nodes']

def hexc(rgb):
    return '#%02x%02x%02x' % tuple(int(v) for v in rgb[:3])

def dist(a, b):
    return sum((x - y) ** 2 for x, y in zip(a[:3], b[:3])) ** 0.5

def region(im, x0, y0, x1, y1):
    return [im.getpixel((x, y)) for y in range(y0, y1) for x in range(x0, x1)]

def med(px):
    return tuple(median(p[i] for p in px) for i in range(3))

def ink(px, bg, min_d=60):
    """Median of the pixels that stand out from the background (digits, text, glyphs)."""
    fg = [p for p in px if dist(p, bg) > min_d]
    return med(fg) if len(fg) >= 4 else None

def parse_pledit(text):
    out = {}
    for key in ('Normal', 'Current', 'NormalBG', 'SelectedBG', 'Font'):
        m = re.search(r'^\s*%s\s*=\s*(.+?)\s*$' % key, text, re.I | re.M)
        if m: out[key] = m.group(1).strip()
    for k in ('Normal', 'Current', 'NormalBG', 'SelectedBG'):
        v = out.get(k, '')
        m = re.match(r'#?([0-9a-f]{6})', v, re.I)
        if not m: return None
        out[k] = '#' + m.group(1).lower()
    return out

def parse_viscolor(text):
    rows = []
    for line in text.splitlines():
        nums = re.findall(r'\d+', line.split('//')[0])
        if len(nums) >= 3: rows.append(tuple(min(255, int(n)) for n in nums[:3]))
    return rows if len(rows) >= 24 else None

def sample(png):
    im = Image.open(io.BytesIO(png)).convert('RGB')
    if im.size != (275, 348): return None
    title = med(region(im, 20, 2, 100, 12))
    frame = med(region(im, 1, 16, 9, 100) + region(im, 0, 108, 275, 115))
    lcd = med(region(im, 24, 24, 100, 60))
    digits = ink(region(im, 48, 26, 92, 40), lcd)
    marquee_bg = med(region(im, 112, 24, 262, 36))
    marquee = ink(region(im, 112, 27, 262, 34), marquee_bg)
    button = med(region(im, 18, 90, 130, 104))
    glyph = ink(region(im, 18, 90, 130, 104), button, 50)
    if digits is None: return None
    return {
        'title': hexc(title), 'frame': hexc(frame), 'lcd': hexc(lcd), 'digits': hexc(digits),
        'marquee': hexc(marquee or digits), 'button': hexc(button), 'glyph': hexc(glyph or title),
    }

def main():
    corpus, offset = [], 0
    while len(corpus) < COUNT:
        nodes = gql(PAGE, offset)
        offset += PAGE
        if not nodes: break
        for n in nodes:
            if len(corpus) >= COUNT: break
            if n.get('nsfw') or not n.get('screenshot_url'): continue
            files = {f['filename'].split('/')[-1].lower(): f.get('text_content') or '' for f in n.get('archive_files') or []}
            pl = parse_pledit(files.get('pledit.txt', ''))
            vis = parse_viscolor(files.get('viscolor.txt', ''))
            if not pl or not vis: continue
            try:
                png = urllib.request.urlopen(urllib.request.Request(n['screenshot_url'], headers={'user-agent': 'music-box-skin-corpus'}), timeout=30).read()
                s = sample(png)
            except Exception as e:
                print('skip', n['filename'], e, file=sys.stderr); continue
            if not s: continue
            s.update({
                'name': re.sub(r'\.(wsz|zip)$', '', n['filename'], flags=re.I)[:48],
                'id': n['md5'],
                'list': [pl['Normal'], pl['Current'], pl['NormalBG'], pl['SelectedBG']],
                'font': (pl.get('Font') or '')[:32],
                # viscolor: 0 background, 2 top of spectrum, 9 middle, 17 bottom, 18 oscilloscope, 23 peak dots
                'vis': [hexc(vis[i]) for i in (0, 2, 9, 17, 18, 23)],
            })
            corpus.append(s)
            print(len(corpus), s['name'], file=sys.stderr)
            time.sleep(0.05)
    with open('js/skin-corpus.js', 'w') as f:
        f.write('// Generated by tools/build_skin_corpus.py from the Winamp Skin Museum (https://skins.webamp.org).\n')
        f.write('// Colors only: each entry is a palette sampled from a classic skin, credited by name and museum id.\n')
        f.write('// title/frame/lcd/digits/marquee/button/glyph come from the screenshot; list = playlist\n')
        f.write('// [text, current, background, selected]; vis = [bg, spectrum top, mid, bottom, scope, peak].\n')
        f.write('export const CORPUS = ')
        json.dump(corpus, f, separators=(',', ':'))
        f.write(';\n')
    print('wrote', len(corpus), 'palettes', file=sys.stderr)

if __name__ == '__main__':
    main()
